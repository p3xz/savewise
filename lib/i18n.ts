const LANG_KEY = 'savewise.language.v1';

export async function loadLanguage(): Promise<Lang> {
  try {
    const raw = await AsyncStorage.getItem(LANG_KEY);
    if (raw && (LANGS as { code: string }[]).some((l) => l.code === raw)) {
      return raw as Lang;
    }
  } catch {
    // Fall through to the default.
  }
  return 'en';
}

export async function saveLanguage(lang: Lang): Promise<void> {
  await AsyncStorage.setItem(LANG_KEY, lang);
}

export type TranslateFn = (
  key: StringKey,
  params?: Record<string, string | number>
) => string;

export function t(
  lang: Lang,
  key: StringKey,
  params?: Record<string, string | number>
): string {
  let s: string = STRINGS[lang][key] ?? STRINGS.en[key];
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      s = s.split(`{${name}}`).join(String(value));
    }
  }
  return s;
}

export function categoryLabel(lang: Lang, category: string): string {
  return t(lang, `cat.${category.toLowerCase()}` as StringKey);
}

export function sourceLabel(lang: Lang, source: string): string {
  return t(lang, `src.${source.toLowerCase()}` as StringKey);
}

export function useLanguage(): {
  lang: Lang;
  setLang: (lang: Lang) => Promise<void>;
  t: TranslateFn;
} {
  const [lang, setLangState] = useState<Lang>('en');

  useEffect(() => {
    loadLanguage().then(setLangState);
  }, []);

  const setLang = useCallback(async (next: Lang) => {
    setLangState(next);
    await saveLanguage(next);
  }, []);

  const translate = useCallback<TranslateFn>(
    (key, params) => t(lang, key, params),
    [lang]
  );

  return { lang, setLang, t: translate };
}
